function sprig(ink, x, y, size, color, tilt = 0) {
  const top = x + size * tilt;
  ink.beam([[x,y],[x+(top-x)*.42,y-size*.5],[top,y-size]], '#425738', 1.5);
  for (let i=1;i<=5;i++) {
    const ratio = i/6, leaf = size*(.17-i*.009), lx=x+(top-x)*ratio, ly=y-size*ratio;
    ink.oval(lx-leaf*.75, ly-leaf*.36, leaf, leaf*.43, color, null, 1, .49);
    ink.oval(lx+leaf*.78, ly-leaf*.56, leaf, leaf*.44, color, null, 1, -.57);
  }
  ink.oval(top, y-size + 3, size*.045, size*.10, color, null, 1, tilt*.5);
}

function pot(ink, x, y, w, h, color) {
  const { box, oval, path, beam } = ink;
  oval(x, y+h+2, w*.59, 4, '#293c32');
  path([[x-w*.44,y],[x+w*.44,y],[x+w*.29,y+h],[x-w*.32,y+h]], color, '#39382a', 1.5);
  path([[x-w*.44,y+4],[x+w*.44,y+4],[x+w*.38,y+11],[x-w*.39,y+11]], '#4c473e69');
  box(x-w*.5,y-4,w,8,color,'#4d493a',1);
  beam([[x-w*.30,y+12],[x-w*.22,y+h-4]], '#f3cd9d63', 1.4);
}

function bloom(ink, x, y, color) {
  ink.beam([[x-1,y+29],[x+1,y+15],[x,y]], '#45664f', 1.8);
  for (let i=0;i<5;i++) {
    const turn = i*Math.PI*2/5;
    ink.oval(x+Math.cos(turn)*5,y+Math.sin(turn)*5,4.8,2.7,color,null,1,turn);
  }
  ink.oval(x,y,2.6,2.7,'#f8d59b');
}

