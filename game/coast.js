  for (let i=0;i<34;i++) {
    const x = 285+random()*187, y = 303+random()*26, r = 1+random()*4;
    if (x < 310 && y < 312) continue;
    beam([[x-r,y],[x,y-r],[x+1,y-1],[x+r,y-r*.6]], i%3 ? '#4d6656' : '#d6ba87', 1.3);
  }
  beam([[241,349],[265,353],[284,352]], '#b2cac2', 2);
  beam([[299,378],[336,385],[381,382],[413,374]], '#9db5ad', 2);
  beam([[438,359],[462,350],[491,344]], '#b7c6ac', 1.3);

