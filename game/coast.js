  const { box, path, oval, beam, sky, label } = ink;
  const random = seeded(410);
  sky('#252c49', '#c27660', 230);
  if (changed) crescent(ctx, 122, 77, 23, '#ffe3ab');
  else oval(122, 77, 23, 23, '#ffe3ab');
  for (const [x, y, s] of [[48,44,2], [202,67,3], [173,30,1], [284,33,2], [332,75,2], [518,35,2], [584,86,3], [608,51,1]]) {
    beam([[x-s,y],[x+s,y]], '#ffe5af', 1);
    beam([[x,y-s],[x,y+s]], '#ffe5af', 1);
  }
  path([[0,130],[62,116],[160,124],[231,104],[312,106],[277,112],[222,119],[165,136],[88,132],[0,150]], '#e29b7448');
