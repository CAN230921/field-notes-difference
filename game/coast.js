  path([[640,189],[607,179],[579,165],[534,195],[487,207],[430,219],[640,239]], '#605263');

  const sea = ctx.createLinearGradient(0, 210, 0, 450);
  sea.addColorStop(0, '#518481');
  sea.addColorStop(.72, '#235a62');
  sea.addColorStop(1, '#173742');
  box(0, 220, 640, 230, sea);
  const reflection = ctx.createLinearGradient(0, 224, 0, 342);
  reflection.addColorStop(0, '#f4ba865a');
  reflection.addColorStop(1, '#e49e6200');
  path([[53,224],[199,224],[239,335],[5,335]], reflection);
  for (let i = 0; i < 210; i++) {
    const x = random()*640, y = 222+random()*228, length = (3+random()*37)*(.4+(y-222)/210);
    beam([[x,y],[x+length*.33,y-.4],[x+length,y]], i%4 ? '#baceaa40' : '#f5b78e72', i%11 ? 1 : 2);
  }
  for (const [x,y,size] of [[61,319,63],[92,367,106],[462,383,111],[514,243,49],[538,419,102],[27,435,59]]) {
    beam([[x,y],[x+size*.25,y-5],[x+size*.66,y-3],[x+size,y-4]], '#91b3a67d', 1.6);
  }

  path([[249,346],[265,310],[296,296],[328,283],[375,281],[414,272],[459,277],[471,295],[502,323],
    [477,338],[451,341],[430,364],[359,378],[307,371],[288,363]], '#5a5756', '#333e46', 2);
