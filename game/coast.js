  path([[399,165],[411,165],[424,296],[401,296]], '#c3a789');
  path([[370,200],[415,200],[419,235],[367,235]], '#c87561');
  path([[399,200],[415,200],[419,235],[401,235]], '#a4534f');
  box(384, 179, 11, 16, '#343d49', '#9d7a64', 2);
  box(384, 243, 11, 14, '#343d49', '#9d7a64', 2);
