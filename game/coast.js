  path([[0,428],[34,408],[58,408],[80,423],[109,424],[137,444],[47,439],[0,450]], '#526056');
  path([[640,403],[610,391],[579,401],[553,421],[524,429],[495,450],[640,450]], '#203743');
  path([[640,419],[610,402],[577,418],[568,430],[532,444],[616,437],[640,446]], '#526455');
