  box(379,131,29,24, '#ffe7a7');
  for (const x of [381,393,405]) beam([[x,130],[x,157]], '#554954', 2.5);
  if (changed) beam([[376,144],[412,144]], '#554954', 2.5);
  path([[369,128],[379,112],[391,102],[405,111],[420,128]], '#79526a', '#343446', 2);
  beam([[391,103],[391,77],[413,57]], '#3b384b', 3);
  path(changed ? [[412,56],[437,50],[433,64],[414,68]] : [[412,56],[441,62],[414,69]], '#e89a72', '#422f41', 1);
